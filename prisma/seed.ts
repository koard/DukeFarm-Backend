async function main() {
  for (const d of diseases) {
    const { tags, ...rest } = d;
    await prisma.disease.upsert({
      where: { name: d.name },
      update: {
        ...rest,
        tags: {
          deleteMany: {},
          create: tags.map((label) => ({ label })),
        },
      },
      create: {
        ...rest,
        tags: { create: tags.map((label) => ({ label })) },
      },
    });
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
