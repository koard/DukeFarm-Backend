async function main() {
        console.log('🗑️ Deleting old disease data...');
        await prisma.diseaseSymptom.deleteMany({});
        await prisma.disease.deleteMany({});
        console.log('✅ Old disease data deleted');

        console.log('🗑️ Deleting old feed formula data...');
        await prisma.feedFormula.deleteMany({});
        console.log('✅ Old feed formula data deleted');

        console.log('📝 Seeding new diseases...');
        for (const d of diseases) {
                const { tags, ...rest } = d;
                await prisma.disease.create({
                        data: {
                                ...rest,
                                tags: { create: tags.map((label) => ({ label })) },
                        },
                });
        }
        console.log(`✅ Seeded ${diseases.length} diseases`);

        console.log('📝 Seeding new feed formulas...');
        for (const formula of feedFormulas) {
                await prisma.feedFormula.create({
                        data: formula,
                });
        }
        console.log(`✅ Seeded ${feedFormulas.length} feed formulas`);
}

main()
        .catch((e) => {
                console.error(e);
                process.exit(1);
        })
        .finally(async () => {
                await prisma.$disconnect();
        });
