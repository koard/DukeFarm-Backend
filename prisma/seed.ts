async function main() {
        console.log('🌱 Starting database seeding...');

        // Seed diseases
        console.log('📋 Seeding diseases...');
        for (const d of diseases) {
                const { tags, ...rest } = d;
                await prisma.disease.upsert({
                        where: { name: d.name },
                        update: {
                                ...rest,
                                tags: {
                                        deleteMany: {},
                                        create: tags.map((label) => ({ label })),
                                },
                        },
                        create: {
                                ...rest,
                                tags: { create: tags.map((label) => ({ label })) },
                        },
                });
        }
        console.log(`✅ Seeded ${diseases.length} diseases`);

        // Seed feed formulas
        console.log('🍽️  Seeding feed formulas...');

        // Delete existing feed formulas to avoid duplicates (since name is not unique)
        await prisma.feedFormula.deleteMany({});

        for (const f of feedFormulas) {
                await prisma.feedFormula.create({
                        data: {
                                name: f.name,
                                targetStage: f.targetStage,
                                farmType: f.farmType as any, // Cast string to FarmType enum
                                ingredients: f.ingredients,
                                instruction: f.instruction,
                                recommendations: f.recommendations,
                        },
                });
        }
        console.log(`✅ Seeded ${feedFormulas.length} feed formulas`);
        console.log('🎉 Database seeding completed successfully!');
}

main()
        .catch((e) => {
                console.error(e);
                process.exit(1);
        })
        .finally(async () => {
                await prisma.$disconnect();
        });
